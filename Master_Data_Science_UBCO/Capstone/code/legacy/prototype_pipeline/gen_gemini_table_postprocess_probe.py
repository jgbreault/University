        "def is_blank(value):\n"
        "    if value is None:\n"
        "        return True\n"
        "    try:\n"
        "        if pd.isna(value):\n"
        "            return True\n"
        "    except Exception:\n"
        "        pass\n"
        "    return str(value).strip() == ''\n\n"
        "def clean(value):\n"
        "    return '' if is_blank(value) else str(value).strip()\n\n"
        "def norm(value):\n"
        "    return re.sub(r'\\s+', ' ', clean(value).lower()).strip()\n\n"
        "def numeric_value(value):\n"
        "    text = clean(value).replace(',', '')\n"
        "    m = re.search(r'-?\\d+(?:\\.\\d+)?', text)\n"
        "    return m.group(0) if m else text\n\n"
        "def normalize_unit(unit):\n"
        "    u = norm(unit)\n"
        "    if u in {'%', 'percent', 'percentage'}:\n"
        "        return 'percent'\n"
        "    if u in {'m', 'meter', 'meters', 'metre', 'metres'}:\n"
        "        return 'm'\n"
        "    if u in {'sq. m', 'sq m', 'm2', 'square metre', 'square metres', 'square meter', 'square meters'}:\n"
        "        return 'sq. m'\n"
        "    if 'storey' in u or 'story' in u:\n"
        "        return 'storeys'\n"
        "    if 'unit' in u:\n"
        "        return 'units'\n"
        "    return u\n\n"
        "def infer_height_subject(evidence_id, row_label, value, unit, condition):\n"
        "    text = norm(evidence_lookup.get(evidence_id, {}).get('text', ''))\n"
        "    row = norm(row_label)\n"
        "    val = numeric_value(value)\n"
        "    cond = norm(condition)\n"
        "    if 'accessory' in row or 'accessory' in text:\n"
        "        return 'accessory_building'\n"
        "    if val in {'10', '10.0', '9.5', '3', '3.0', '2.5'} and evidence_id.endswith(('row_001', 'row_002')):\n"
        "        return 'front_principal_building'\n"
        "    if val in {'7.5', '7.0', '2', '2.0'} and evidence_id.endswith(('row_004', 'row_005')):\n"
        "        return 'rear_principal_building'\n"
        "    if val in {'10', '10.0', '9.5'}:\n"
        "        return 'front_principal_building'\n"
        "    if val in {'7.5', '7.0'}:\n"
        "        return 'rear_principal_building'\n"
        "    return 'building'\n\n"
        "def normalize_rule_key_offline(rule):\n"
