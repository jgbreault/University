        "    row = norm(rule.get('row_label'))\n"
        "    unit = normalize_unit(rule.get('unit'))\n"
        "    value = numeric_value(rule.get('value'))\n"
        "    condition = norm(rule.get('condition'))\n"
        "    eid = clean(rule.get('evidence_id'))\n\n"
        "    if 'permitted dwelling units' in row:\n"
        "        return 'permitted_dwelling_units'\n"
        "    if 'minimum lot area' in row:\n"
        "        return 'min_lot_area'\n"
        "    if 'maximum lot area' in row:\n"
        "        return 'max_lot_area'\n"
        "    if 'lot coverage' in group and 'impervious' in row:\n"
        "        return 'max_impervious_surface'\n"
        "    if 'lot coverage' in group:\n"
        "        return 'max_lot_coverage_all_buildings'\n"
        "    if group == 'height':\n"
        "        subject = infer_height_subject(eid, row, value, unit, condition)\n"
        "        if unit == 'storeys':\n"
        "            return f'max_{subject}_storeys'\n"
        "        if 'flat' in condition:\n"
        "            return f'max_{subject}_height_flat_roof'\n"
        "        if 'sloping' in condition or 'sloped' in condition:\n"
        "            return f'max_{subject}_height_sloped_roof'\n"
        "        return f'max_{subject}_height'\n"
        "    if 'setback' in group or 'yard' in row:\n"
        "        if 'street yard' in row:\n"
        "            return 'min_street_yard_setback'\n"
        "        if 'lane yard' in row:\n"
        "            return 'min_lane_yard_setback'\n"
        "        if 'interior rear' in row:\n"
        "            return 'min_interior_rear_yard_setback'\n"
        "        if 'interior side' in row:\n"
        "            return 'min_interior_side_yard_setback'\n"
        "    if 'between' in group or 'between' in row:\n"
        "        if 'front & rear' in row or 'front and rear' in row:\n"
        "            return 'min_separation_between_front_and_rear_principals'\n"
        "        if 'rear principals' in row:\n"
        "            return 'min_separation_between_rear_principals'\n"
        "        if 'front principals' in row:\n"
        "            return 'min_separation_between_front_principals'\n"
        "        if 'all other buildings' in row:\n"
        "            return 'min_separation_between_all_other_buildings'\n"
        "    return re.sub(r'[^a-z0-9]+', '_', norm(rule.get('rule_key_suggestion'))).strip('_') or 'unknown_rule'\n\n"
        "def normalize_operator_offline(rule):\n"
